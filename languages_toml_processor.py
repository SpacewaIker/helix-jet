import sys
import toml
import tomllib
import argparse


def flatten(prefix: str, data: dict, out: dict):
    for key, value in data.items():
        full_key = f"{prefix}.{key}"
        if isinstance(value, dict):
            flatten(full_key, value, out)
        elif isinstance(value, list):
            for i, item in enumerate(value):
                if isinstance(item, dict):
                    flatten(f"{full_key}.{i}", item, out)
                else:
                    out[f"{full_key}.{i}"] = item
        else:
            out[full_key] = value


def grammars(args):
    """
        Copy over every [[grammar]] entry from languages.toml.
        Flatten structure such as follows:

        languages.toml:
        [[grammar]]
        name = "python"
        source = { git = "https://github.com/...", subpath = "...", rev = "..." }

        languages.properties:
        grammar.python.source.git=https://github.com/...
        grammar.python.source.subpath=...
        grammar.python.source.rev=...
    """
    with open(args.input, "rb") as f:
        data = tomllib.load(f)

    languages = set(args.languages) if args.languages else None

    with open(args.output, "w") as f:
        f.write("# Autogenerated with languages_toml_processor.py. Do not modify.\n")
        for grammar in data["grammar"]:
            name = grammar["name"]

            if languages and name not in languages:
                continue

            props = {}
            flatten(f"grammar.{name}", {k: v for k, v in grammar.items() if k != "name"}, props)
            for key, value in props.items():
                f.write(f"{key}={value}\n")


def languages(args):
    """
        Copy over some fields from every [[language]] entry from languages.toml.
        ktoml doesn't support arrays of multiple types, so we separate file-types into file-types-str and file-types-glob.
    """
    with open(args.input, "rb") as f:
        data = tomllib.load(f)

    languages_to_include = set(args.languages) if args.languages else None
    languages = []
    
    for language in data["language"]:
        name = language["name"]

        if languages_to_include and name not in languages_to_include:
            continue

        language_new = {"name": name}

        # file-types
        file_types = language["file-types"]
        str_file_types = [f for f in file_types if isinstance(f, str)]
        dict_file_types = [f["glob"] for f in file_types if isinstance(f, dict)]
                    
        if len(str_file_types) > 0:
            language_new["file-types-str"] = str_file_types
        if len(dict_file_types) > 0:
            language_new["file-types-glob"] = dict_file_types

        # comment tokens
        comment_tokens = []
        for key in ["comment-token", "comment-tokens"]:
            if key in language:
                val = language[key]
                if isinstance(val, str):
                    comment_tokens.append(val)
                elif isinstance(val, list):
                    comment_tokens.extend(val)
        for i, token in enumerate(comment_tokens):
            if token == "\\":  # ktoml can't parse ["\\"], so use unicode/ascii code
                comment_tokens[i] = "\\x5c"
            elif token == "*":
                comment_tokens[i] = "\\x2a"
        if len(comment_tokens) > 0:
            language_new["comment-tokens"] = comment_tokens

        # block comment tokens
        block_comment_tokens = []
        if "block-comment-tokens" in language:
            val = language["block-comment-tokens"]
            if isinstance(val, dict):
                block_comment_tokens.append(val)
            elif isinstance(val, list):
                if isinstance(val[0], dict):
                    block_comment_tokens.extend(val)
                elif isinstance(val[0], str) and len(val) == 2:
                    block_comment_tokens.append({"start": val[0], "end": val[1]})
        for i, token in enumerate(block_comment_tokens):
            if "\\" in token:
                block_comment_tokens[i] = token.replace("\\", "\\x5c")
            if "*" in token:
                block_comment_tokens[i] = token.replace("*", "\\x2a")
        if len(block_comment_tokens) > 0:
            language_new["block-comment-tokens"] = block_comment_tokens

        for key in ["grammar", "indent"]:
            if key in language:
                language_new[key] = language[key]

        languages.append(language_new)

    with open(args.output, "w", encoding="utf-8") as f:
        f.write("# Autogenerated with languages_toml_processor.py. Do not modify.\n")
        toml.dump({"language": languages}, f)


parser = argparse.ArgumentParser()
subparsers = parser.add_subparsers()

grammars_parser = subparsers.add_parser("grammars", help="Generate languages.properties containing the grammar definitions from languages.toml")
grammars_parser.add_argument("input", help="Input languages.toml")
grammars_parser.add_argument("output", help="Output properties file")
grammars_parser.add_argument("--languages", nargs="*", help="Languages to include (default: all)")
grammars_parser.set_defaults(func=grammars)

languages_parser = subparsers.add_parser("languages", help="Generate ktoml-valid languages.toml containing language definitions with single-type arrays")
languages_parser.add_argument("input", help="Input languages.toml")
languages_parser.add_argument("output", help="Output languages.toml")
languages_parser.add_argument("--languages", nargs="*", help="Languages to include (default: all)")
languages_parser.set_defaults(func=languages)


args = parser.parse_args()
args.func(args)
